/** Linear chain: each concept requires the immediately previous one. */
export const PREREQUISITES: Record<string, string[]> = Object.fromEntries(
  CONCEPTS.slice(1).map((c, i) => [c.id, [CONCEPTS[i].id]])
);

export function getConceptById(id: string): Concept | undefined {
  return CONCEPTS.find((c) => c.id === id);
}

export function getConceptsByUnit(unitId: string): Concept[] {
  return CONCEPTS.filter((c) => c.unitId === unitId).sort(
    (a, b) => a.order - b.order
  );
}

export function getSortedConcepts(): Concept[] {
  return [...CONCEPTS].sort((a, b) => a.order - b.order);
}
