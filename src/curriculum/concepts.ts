import type { Concept } from "@/lib/types";

/**
 * Ordered N5 curriculum concepts. The learning engine walks this list
 * and respects prerequisites + mastery before advancing.
 */

function concept(
  partial: Omit<Concept, "contentIds" | "estimatedMinutes"> & {
    estimatedMinutes?: number;
  }
): Concept {
  const vocabularyIds = partial.vocabularyIds ?? [];
  const grammarIds = partial.grammarIds ?? [];
  const kanjiIds = partial.kanjiIds ?? [];
  const kanaIds = partial.kanaIds ?? [];
  return {
    estimatedMinutes: 20,
    ...partial,
    vocabularyIds,
    grammarIds,
    kanjiIds,
    kanaIds,
    contentIds: [...vocabularyIds, ...grammarIds, ...kanjiIds, ...kanaIds],
  };
}

